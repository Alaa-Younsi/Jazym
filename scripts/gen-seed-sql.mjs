/* One-off: emit supabase/migrations/0008_seed.sql from the bundled demo
   catalogue so the DB seed and the demo-mode storefront never diverge.
   Run: `bun run scripts/gen-seed-sql.mjs` */

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { DEMO_CATEGORIES, DEMO_PRODUCTS, DEMO_REVIEWS } from "../src/data/demo.ts";
import { WILAYAS } from "../src/lib/wilayas.ts";

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) =>
  a && a.length ? `array[${a.map((x) => q(x)).join(",")}]::text[]` : `'{}'::text[]`;
const jsonb = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

let sql = `-- Jazym seed data — generated by scripts/gen-seed-sql.mjs. Do not hand-edit.
-- Idempotent: re-running upserts by slug / wilaya. Add real product photos via
-- the admin (this seed sets no product_images rows).

begin;

`;

// Categories
sql += "-- categories --------------------------------------------------------\n";
for (const c of DEMO_CATEGORIES) {
  sql += `insert into public.categories (slug, name_fr, name_ar, description_fr, description_ar, sort_order) values (${q(
    c.slug,
  )}, ${q(c.name_fr)}, ${q(c.name_ar)}, ${q(c.description_fr)}, ${q(c.description_ar)}, ${c.sort_order})
on conflict (slug) do update set name_fr=excluded.name_fr, name_ar=excluded.name_ar,
  description_fr=excluded.description_fr, description_ar=excluded.description_ar, sort_order=excluded.sort_order;
`;
}

// Products
sql += "\n-- products ---------------------------------------------------------\n";
const slugByCat = Object.fromEntries(DEMO_CATEGORIES.map((c) => [c.id, c.slug]));
for (const p of DEMO_PRODUCTS) {
  const catSlug = slugByCat[p.category_id ?? ""] ?? null;
  sql += `insert into public.products
  (slug, name_fr, name_ar, description_fr, description_ar, details_fr, details_ar,
   price, compare_at_price, category_id, stock, style_code, colors, sizes, variants,
   quantity_offers, featured, status)
values (${q(p.slug)}, ${q(p.name_fr)}, ${q(p.name_ar)}, ${q(p.description_fr)}, ${q(
    p.description_ar,
  )}, ${arr(p.details_fr)}, ${arr(p.details_ar)}, ${p.price}, ${
    p.compare_at_price ?? "null"
  }, ${catSlug ? `(select id from public.categories where slug = ${q(catSlug)})` : "null"}, ${
    p.stock
  }, ${q(p.style_code)}, ${jsonb(p.colors)}, ${jsonb(p.sizes)}, ${jsonb(p.variants)}, ${jsonb(
    p.quantity_offers,
  )}, ${p.featured}, ${q(p.status)})
on conflict (slug) do update set
  name_fr=excluded.name_fr, name_ar=excluded.name_ar,
  description_fr=excluded.description_fr, description_ar=excluded.description_ar,
  details_fr=excluded.details_fr, details_ar=excluded.details_ar,
  price=excluded.price, compare_at_price=excluded.compare_at_price,
  category_id=excluded.category_id, stock=excluded.stock, style_code=excluded.style_code,
  colors=excluded.colors, sizes=excluded.sizes, variants=excluded.variants,
  quantity_offers=excluded.quantity_offers, featured=excluded.featured, status=excluded.status;
`;
}

// Delivery prices — zone-based estimate (north <=48 vs south).
sql += "\n-- delivery prices (69 wilayas) -----------------------------------\n";
sql += `insert into public.delivery_prices (wilaya, home_price, office_price)
select w.name,
       case when w.code <= 48 then 500 else 800 end,
       case when w.code <= 48 then 300 else 500 end
from (values
${WILAYAS.map((w) => `  (${w.code}, ${q(w.name_fr)})`).join(",\n")}
) as w(code, name)
on conflict (wilaya) do nothing;
`;

// Reviews
sql += "\n-- reviews ---------------------------------------------------------\n";
for (const r of DEMO_REVIEWS) {
  sql += `insert into public.client_reviews (client_name, stars, review_text, active) values (${q(
    r.client_name,
  )}, ${r.stars}, ${q(r.review_text)}, true);
`;
}

// Store settings announcement
sql += `\n-- store settings ------------------------------------------------\n`;
sql += `update public.store_settings set
  announcement_fr = 'Livraison partout en Algérie · Paiement à la livraison',
  announcement_ar = 'توصيل إلى كامل الوطن · الدفع عند الاستلام'
where id = 1;
`;

sql += "\ncommit;\n";

const out = fileURLToPath(new URL("../supabase/migrations/0008_seed.sql", import.meta.url));
await writeFile(out, sql, "utf8");
console.log(`0008_seed.sql — ${DEMO_PRODUCTS.length} products, ${WILAYAS.length} wilayas`);
