/* Emit src/data/communes.ts — the 1,541 communes of the 69 wilayas (Loi 26-06,
   4 April 2026), keyed by the wilaya codes in src/lib/wilayas.ts. Source is the
   MIT-licensed geoalgeria dataset, pinned so a re-run is reproducible; bump
   GEOALGERIA_VERSION to pull a newer revision.
   Run: `bun run scripts/gen-communes.mjs` */

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { WILAYAS } from "../src/lib/wilayas.ts";

const GEOALGERIA_VERSION = "2.3.0";
const SOURCE = `https://cdn.jsdelivr.net/npm/geoalgeria@${GEOALGERIA_VERSION}/data/ecommerce/communes.json`;
const EXPECTED_TOTAL = 1541;

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} → ${res.status}`);
const rows = await res.json();

if (rows.length !== EXPECTED_TOTAL) {
  throw new Error(`expected ${EXPECTED_TOTAL} communes, got ${rows.length}`);
}

/** @type {Map<number, [string, string][]>} */
const byWilaya = new Map(WILAYAS.map((w) => [w.code, []]));
for (const r of rows) {
  const list = byWilaya.get(r.wilaya_code);
  if (!list) throw new Error(`unknown wilaya code ${r.wilaya_code} (${r.commune_name_fr})`);
  list.push([r.commune_name_fr.trim(), r.commune_name_ar.trim()]);
}
for (const [code, list] of byWilaya) {
  if (list.length === 0) throw new Error(`wilaya ${code} has no communes`);
  list.sort((a, b) => a[0].localeCompare(b[0], "fr"));
}

const body = [...byWilaya]
  .map(([code, list]) => `  ${code}: [\n${list.map(([fr, ar]) => `    [${JSON.stringify(fr)}, ${JSON.stringify(ar)}],`).join("\n")}\n  ],`)
  .join("\n");

const ts = `/* GENERATED by scripts/gen-communes.mjs from geoalgeria@${GEOALGERIA_VERSION}
   (MIT, https://github.com/yasserstudio/geoalgeria). Do not hand-edit.
   ${rows.length} communes across the 69 wilayas of Loi 26-06 (4 April 2026).
   Loaded lazily by the checkout — keep it out of the main bundle. */

/** [French name, Arabic name]. The French name is what an order stores. */
export type Commune = readonly [fr: string, ar: string];

export const COMMUNES: Readonly<Record<number, readonly Commune[]>> = {
${body}
};
`;

const out = fileURLToPath(new URL("../src/data/communes.ts", import.meta.url));
await writeFile(out, ts);
console.log(`wrote ${rows.length} communes for ${byWilaya.size} wilayas → ${out}`);
